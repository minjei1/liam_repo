function isInSeason(item, month) {
  if (item.start <= item.end) return month >= item.start && month <= item.end;
  return month >= item.start || month <= item.end;
}

function recipeMarkup(name, compact) {
  var r = RECIPES[name];
  if (!r) return "";
  return (
    '<div class="recipe">' +
      (compact ? "" : '<p class="recipe-title">' + name + '</p>' + '<p class="recipe-desc">' + r.d + '</p>') +
      '<p class="recipe-label">재료</p>' +
      '<ul class="recipe-ingredients">' + r.i.map(function (x) { return "<li>" + x + "</li>"; }).join("") + '</ul>' +
      '<p class="recipe-label">만드는 법</p>' +
      '<ol class="recipe-steps">' + r.s.map(function (x) { return "<li>" + x + "</li>"; }).join("") + '</ol>' +
    '</div>'
  );
}

